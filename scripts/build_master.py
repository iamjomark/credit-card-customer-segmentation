"""Builds notebooks/00_master.ipynb by merging notebooks 01 to 04 (code and text only, no outputs).
Run: uv run python scripts/build_master.py   then execute the result with nbconvert."""
import sys
from pathlib import Path

import nbformat
from nbformat.v4 import new_code_cell, new_markdown_cell, new_notebook

sys.path.insert(0, str(Path(__file__).parent))
from nbtools import save

ROOT = Path(__file__).parent.parent
NOTEBOOKS = ROOT / "notebooks"

# (file stem, part title, which steps it holds)
PARTS = [
    ("01_eda", "Exploratory data analysis", "Steps 1 to 4: profiling, univariate EDA and normality, correlation, missing values and outliers"),
    ("02_preprocessing", "Preprocessing and dimensionality reduction", "Steps 5 and 6: transforms, the preprocessing pipeline, PCA"),
    ("03_clustering", "Clustering and cluster profiling", "Steps 7 and 8: KMeans metrics, stability, other methods, robustness checks, profiles and names"),
    ("04_explainability", "Explainability", "Step 9: surrogate model, SHAP, distance contributions, permutation importance"),
]

cells = [new_markdown_cell(f"""
# Customer segmentation of credit card holders: master notebook

**Business question:** Which groups of credit card customers exist, based on how they spend, pay and borrow, and what does each group look like in business terms?

This notebook is the whole project in one place, from the first look at the data to the business conclusions. It is generated by `scripts/build_master.py` from the four step-by-step notebooks (`01_eda`, `02_preprocessing`, `03_clustering`, `04_explainability`), so the two versions always say the same thing. Use whichever you prefer: this one to read top to bottom, the four to work on one stage at a time.

## Contents

""" + "\n".join(f"{number}. **Part {number}: {title}** ({steps})" for number, (_, title, steps) in enumerate(PARTS, start=1)) + """
5. **Part 5: Conclusions and deliverables** (Step 10: business summary, limitations, next steps)

## How to use it

- **Run it top to bottom.** Each part saves files into `data/processed/` that the next part reads, so the order matters. The full run takes roughly 10 minutes (the SHAP and bootstrap steps are the slow ones).
- You need the data at `data/raw/credit_card.csv` (it is not stored in git).
- Some setup cells (finding the project folder, loading the data) appear again at the start of each part. They are kept on purpose: it makes each part identical to its stand-alone notebook.
- Every code cell has a short note above it with three lines: what it does, what to look for, what the output means.
""")]

for number, (stem, title, steps) in enumerate(PARTS, start=1):
    source_notebook = nbformat.read(NOTEBOOKS / f"{stem}.ipynb", 4)
    cells.append(new_markdown_cell(
        f"---\n# Part {number}: {title}\n*{steps}. Same content as `notebooks/{stem}.ipynb`.*"))
    for position, cell in enumerate(source_notebook.cells):
        text = cell.source
        if position == 0 and cell.cell_type == "markdown" and text.startswith("# "):
            text = "\n".join(text.splitlines()[1:]).lstrip("\n")   # drop the old title line, the part header replaces it
        if cell.cell_type == "code":
            cells.append(new_code_cell(text))          # fresh code cell: no outputs, no execution count
        elif text.strip():
            cells.append(new_markdown_cell(text))

summary = (ROOT / "reports" / "business_summary.md").read_text()
summary_body = "\n".join(summary.splitlines()[1:]).lstrip("\n")   # drop the file's H1 title
cells.append(new_markdown_cell(
    "---\n# Part 5: Conclusions and deliverables\n"
    "*Step 10. The text below is the same as `reports/business_summary.md`, which is the file to share.*\n\n"
    + summary_body))
cells.append(new_markdown_cell("""
### Project files

- Business summary: `reports/business_summary.md`
- Profiling report: `reports/credit_card_profile.html`
- Figures and cluster profile tables: `reports/figures/`, `reports/cluster_profile_*.csv`
- Saved model, pipeline and labels: `data/processed/` (not stored in git)
- Step-by-step notebooks: `notebooks/01_eda.ipynb` to `04_explainability.ipynb`
"""))

save(cells, NOTEBOOKS / "00_master.ipynb")
print(f"built with {len(cells)} cells")
